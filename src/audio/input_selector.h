#pragma once

// Реле-селектор зовнішніх входів (Computer / Aux).
// [Prompt 48a] Створено; замінює TDA7318 / PT2313L (їх вирізано повністю).
// [D2a] Новий пристрій: логічний 1 = Computer (реле вимкнено, LOW), логічний 2 = Aux (реле увімкнено, HIGH).
//
// ОДНЕ DPDT-реле на ОДНОМУ GPIO (pins::kInputRelay). Вихід реле йде на вхід PCM1808. Радіо (логічний 0)
// і Плеєр (логічний 3) реле НЕ чіпають і стану реле від них не вимагають.
//
// Модуль НЕБЛОКУЮЧИЙ: select() лише виставляє рівень піна. Паузу після перемикання
// (input_selector_cfg::kRelaySettleMs) і цифровий мʼют line_path на цей час забезпечує ВИКЛИКАЧ
// (AppController: мʼют проходу -> select() -> пауза -> розмʼют). Викликати select() без мʼюту
// проходу не можна: клацання реле потрапило б у динаміки.
//
// Потоки: begin() — з setup(), до старту AppController; select() / current() — лише з задачі
// AppController (під її мʼютексом). Власного мʼютекса модуль не має.
//
// Лог (Serial, префікс [SEL]):
//   begin():   "[SEL] relay pin=<n> activeHigh=<0|1> -> Computer"
//   select():  "[SEL] input=<n> relay=<on|off>"   (on = Aux, off = Computer)

#include <stdint.h>

namespace input_selector {

// Налаштовує пін реле як вихід і ставить реле в «вимкнено» (Computer). Повторний виклик безпечний
// (повертає true, пін не чіпає). Завжди true на ESP32 (GPIO налаштовується без помилок).
bool begin();

// Перемикає реле на логічний вхід: 1 -> Computer (реле вимкнено), 2 -> Aux (реле увімкнено).
// Для 0 (радіо), 3 (Плеєр) і будь-якого іншого значення нічого не робить (false). true — реле виставлено
// (також коли воно вже було в потрібному стані: пін перезаписується тим самим рівнем).
// До begin() нічого не робить (false).
bool select(uint8_t logicalInput);

// Логічний вхід, на який зараз виставлено реле: 1 (Computer) або 2 (Aux). До begin() — 1.
// Це стан реле, а НЕ поточний вхід пристрою (на радіо / Плеєрі реле лишається на останньому зовнішньому вході).
uint8_t current();

}  // namespace input_selector
